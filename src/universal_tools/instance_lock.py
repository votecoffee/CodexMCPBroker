"""Small OS-owned state lock shared by the broker and desktop manager."""

import os
from pathlib import Path

from .models import BrokerError


class InstanceLock:
    """An OS-owned lock is released automatically if its process exits or crashes."""

    def __init__(self, path: Path):
        self.path = path
        self.stream = None

    def __enter__(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.stream = self.path.open("a+b")
        if self.path.stat().st_size == 0:
            self.stream.write(b"0")
            self.stream.flush()
        self.stream.seek(0)
        try:
            if os.name == "nt":
                import msvcrt

                msvcrt.locking(self.stream.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl

                fcntl.flock(self.stream.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            self.stream.close()
            raise BrokerError("another process already owns this state directory") from None
        return self

    def __exit__(self, *args):
        self.stream.close()
